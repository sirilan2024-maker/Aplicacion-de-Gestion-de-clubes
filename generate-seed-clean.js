function buildInsert(ex) {
  const objTec = "ARRAY[" + (ex.objetivo_tecnico || ['pase']).map(o => `'${o.replace(/'/g, "''")}'`).join(", ") + "]";
  const objTac = "ARRAY[" + (ex.objetivo_tactico || ['apoyo']).map(o => `'${o.replace(/'/g, "''")}'`).join(", ") + "]";
  const catArray = "ARRAY['" + (ex.categoria_edad ? ex.categoria_edad.join("','") : (ex.age_category || 'general')) + "']";
  const cat = ex.age_category || (ex.categoria_edad ? ex.categoria_edad[0] : 'general');
  const materialArray = "ARRAY[" + (ex.material || ['balones', 'conos', 'petos']).map(m => `'${m}'`).join(", ") + "]";
  const variantesArray = "ARRAY[" + (ex.variantes || ['Variante 1']).map(v => `'${v.replace(/'/g, "''")}'`).join(", ") + "]";
  const tagsArray = "ARRAY[" + (ex.tags || [cat, ex.tipo, ex.familia]).map(t => `'${t}'`).join(", ") + "]";
  const criteriosArray = "ARRAY[" + (ex.criterios_exito || ['Ejecución técnica correcta']).map(c => `'${c.replace(/'/g, "''")}'`).join(", ") + "]";

  return `INSERT INTO public.banco_ejercicios (
    club_id,
    nombre, tipo, familia, fuente, descripcion,
    organizacion, distribucion_inicial, desarrollo, rotaciones, puntuacion, intervenciones, correcciones,
    objetivo_tecnico, objetivo_tactico,
    categoria_edad, age_category,
    dificultad, duracion_recomendada,
    min_players, max_players,
    material, variantes, tags,
    bloque_sesion, carga_fisica, carga_cognitiva, oposicion, representatividad,
    intensity_level, game_phase, drill_structure,
    espacio, criterios_exito, progresion_descripcion, regresion_descripcion,
    is_validated
) VALUES (
    (SELECT id FROM public.clubs LIMIT 1),
    '${ex.nombre.replace(/'/g, "''")}',
    '${ex.tipo}',
    '${ex.familia || 'TÁCTICA OFENSIVA'}',
    '${(ex.fuente || 'Adaptación metodológica').replace(/'/g, "''")}',
    '${ex.descripcion.replace(/'/g, "''")}',
    '${(ex.organizacion || ex.espacio).replace(/'/g, "''")}',
    '${(ex.distribucion_inicial || 'Posicionamiento táctico según rol').replace(/'/g, "''")}',
    '${(ex.desarrollo || ex.descripcion).replace(/'/g, "''")}',
    '${(ex.rotaciones || 'Rotación continua').replace(/'/g, "''")}',
    '${(ex.puntuacion || 'Puntuación por objetivos conseguidos').replace(/'/g, "''")}',
    '${(ex.intervenciones || 'Correcciones en pausas activas').replace(/'/g, "''")}',
    '${(ex.correcciones || 'Perfil corporal y precisión técnica').replace(/'/g, "''")}',
    ${objTec},
    ${objTac},
    ${catArray},
    '${cat}',
    ${ex.dificultad || 2},
    ${ex.duracion_recomendada || 15},
    ${ex.min_players || 6},
    ${ex.max_players || 12},
    ${materialArray},
    ${variantesArray},
    ${tagsArray},
    '${ex.bloque_sesion || 'principal'}',
    ${Math.min(4, Math.max(1, ex.carga_fisica || 2))},
    ${Math.min(4, Math.max(1, ex.carga_cognitiva || 2))},
    ${Math.min(4, Math.max(1, ex.oposicion || 2))},
    ${Math.min(4, Math.max(1, ex.representatividad || 3))},
    ${Math.min(5, Math.max(1, ex.intensity_level || 3))},
    '${ex.game_phase || 'attacking_build_up'}',
    '${ex.drill_structure || ex.tipo}',
    '${ex.espacio || '20x20m'}',
    ${criteriosArray},
    '${(ex.progresion_descripcion || 'Reducir espacio y toques').replace(/'/g, "''")}',
    '${(ex.regresion_descripcion || 'Aumentar espacio y añadir comodines').replace(/'/g, "''")}',
    true
) ON CONFLICT DO NOTHING;\n\n`;
}

