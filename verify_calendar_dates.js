function safeParseDateTime(fechaHoraRaw, defaultDateStr) {
  let targetStr = fechaHoraRaw || defaultDateStr || "";
  if (!targetStr) return null;

  const match = targetStr.match(/(\d{1,2})[/.-](\d{1,2})[/.-](\d{2,4})(?:\s*(?:-\s*|\s+)?(\d{1,2}):(\d{2}))?/);
  if (match) {
    const day = parseInt(match[1], 10);
    const month = parseInt(match[2], 10) - 1;
    let year = parseInt(match[3], 10);
    if (year < 100) year += 2000;
    const hour = match[4] ? parseInt(match[4], 10) : 12;
    const min = match[5] ? parseInt(match[5], 10) : 0;

    if (day >= 1 && day <= 31 && month >= 0 && month <= 11 && year >= 2020 && year <= 2035) {
      const d = new Date(year, month, day, hour, min);
      if (!isNaN(d.getTime())) return d;
    }
  }
  return null;
}

function parseTest() {
  const lines = userPdfText.split(/\r?\n/);
  let currentJornada = "";
  let currentJornadaDate = "";

  lines.forEach(line => {
    line = line.trim();
    if (!line) return;

    const jMatch = line.match(/Jornada\s+(\d+)\s*\(([^)]+)\)/i);
    if (jMatch) {
      currentJornada = `Jornada ${jMatch[1]}`;
      currentJornadaDate = jMatch[2].trim();
      return;
    }

    if (line.includes("Campo") && line.includes("Fecha / Hora")) return;

    let fechaHoraRaw = "";
    const dateMatch = line.match(/\d{2}[-/]\d{2}[-/]\d{4}\s*(?:-\s*|\s+)?\d{2}:\d{2}/);
    if (dateMatch) {
      fechaHoraRaw = dateMatch[0];
      line = line.substring(0, dateMatch.index).trim();
    }

    const campoMatch = line.match(/\s+(Campo|Polideportivo|Polidep\.)\s+.*$/i);
    if (campoMatch) {
      line = line.substring(0, campoMatch.index).trim();
    } else {
      line = line.replace(/\s*\((?:HA|HN|H\.A\.|H\.N\.)\)\s*$/i, '').trim();
    }

    line = line.replace(/\t+/g, ' ').replace(/\s+/g, ' ').trim();

    const dashMatch = line.match(/^(.*?)(?:\s+(\d+))?\s*-\s*(?:(\d+)\s+)?(.*)$/);
    if (!dashMatch) return;

    let local = dashMatch[1].replace(/^\d+[\.\s\-]+/, '').trim();
    let visitante = dashMatch[4].replace(/^\d+[\.\s\-]+/, '').trim();

    if (!local || !visitante || /^\d+$/.test(local) || /^\d+$/.test(visitante)) return;

    function isOurClub(str) {
      const norm = str.toLowerCase();
      return norm.includes("saladar") || norm.includes("sporting");
    }

    const localIsUs = isOurClub(local);
    const visitIsUs = isOurClub(visitante);

    if (!localIsUs && !visitIsUs) return;

    const dt = safeParseDateTime(fechaHoraRaw, currentJornadaDate);
    console.log(`[${currentJornada}] ${dt ? dt.toLocaleDateString('es-ES') + ' ' + dt.toLocaleTimeString('es-ES', {hour: '2-digit', minute:'2-digit'}) : 'NO DATE'} | ${localIsUs ? 'Local' : 'Visitante'} vs ${localIsUs ? visitante : local}`);
  });
}

